#!/usr/bin/env node
/*
 * build-map.mjs — generates assets/js/map-data.js, the coastlines for the
 * "ice wall" map (a north-polar azimuthal equidistant projection — the
 * classic flat-earth / Gleason layout, where Antarctica becomes the ring of
 * ice around the edge).
 *
 * Zero dependencies. Input is a world-atlas TopoJSON land file:
 *   npm pack world-atlas@2   (or download land-50m.json from the package)
 *   node tools/build-map.mjs path/to/land-50m.json
 *
 * The output is committed, so this only needs re-running to change detail.
 * Projection (must match assets/js/map.js → project()):
 *   rho = (90 - lat) / 180 * R ;  x = C + rho * sin(lon) ;  y = C + rho * cos(lon)
 *   → north pole in the centre, Greenwich pointing down, east counter-clockwise.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node tools/build-map.mjs land-50m.json'); process.exit(1); }
const topo = JSON.parse(fs.readFileSync(SRC, 'utf8'));

const C = 500, R = 470;           // viewBox 0 0 1000 1000
const MIN_STEP = 1.1;             // drop vertices closer than this (px) to the last kept one
const rad = Math.PI / 180;
const project = ([lon, lat]) => {
  const rho = (90 - lat) / 180 * R;
  return [C + rho * Math.sin(lon * rad), C + rho * Math.cos(lon * rad)];
};

/* --- minimal TopoJSON decode (quantized, delta-encoded arcs) --- */
const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
const arcPoints = (i) => (i < 0 ? arcs[~i].slice().reverse() : arcs[i]);
const ring = (idx) => {
  const pts = [];
  idx.forEach((a, k) => { const p = arcPoints(a); pts.push(...(k ? p.slice(1) : p)); });
  return pts;
};
const polygons = [];
for (const g of topo.objects.land.geometries) {
  if (g.type === 'Polygon') polygons.push(g.arcs.map(ring));
  if (g.type === 'MultiPolygon') g.arcs.forEach((p) => polygons.push(p.map(ring)));
}

const f = (n) => Math.round(n * 10) / 10;
const toPath = (pts, close = true) => {
  let d = '', last = null, n = 0;
  for (const p of pts) {
    const [x, y] = project(p);
    if (last && Math.hypot(x - last[0], y - last[1]) < MIN_STEP) continue;
    d += (n ? 'L' : 'M') + f(x) + ' ' + f(y);
    last = [x, y]; n++;
  }
  return n > 2 ? d + (close ? 'Z' : '') : '';
};

let land = '', ice = '', iceBits = '';
const southern = polygons.filter((poly) => Math.min(...poly[0].map((p) => p[1])) < -60);
const mainland = southern.reduce((a, b) => (b[0].length > a[0].length ? b : a));
for (const poly of polygons) {
  if (poly === mainland) {
    // Antarctica: keep its coast only. The data closes the ring along the
    // pole, which this projection smears round the rim; the page pairs this
    // coast with the rim circle (fill-rule evenodd) so it renders as the ring
    // of ice — the wall.
    ice = toPath(poly[0].filter((p) => p[1] > -89.5));
  } else if (southern.includes(poly)) {
    iceBits += poly.map((r) => toPath(r)).join('');   // sub-Antarctic islands / shelves
  } else {
    land += poly.map((r) => toPath(r)).join('');
  }
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'js', 'map-data.js');
fs.writeFileSync(out,
  '/* generated by tools/build-map.mjs from world-atlas (Natural Earth, public domain) — do not edit */\n' +
  `window.AA_MAP=${JSON.stringify({ C, R, land, ice, iceBits })};\n`);
console.log('wrote', out, (fs.statSync(out).size / 1024).toFixed(1) + ' KB');
